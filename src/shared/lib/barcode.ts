/** عرض‌های متناوب میله/فاصله (با میله شروع می‌شود). کاراکتر خارج از ASCII قابل چاپ رد می‌شود. */
export function code128(text: string): number[] {
  const vals: number[] = [104]
  for (const ch of text) { const c = ch.charCodeAt(0); if (c < 32 || c > 126) throw new Error('کاراکتر غیرمجاز برای Code 128'); vals.push(c - 32) }
  const check = vals.reduce((s, v, i) => s + v * (i === 0 ? 1 : i), 0) % 103
  return [...vals, check, 106].flatMap((v) => C128[v].split('').map(Number))
}

const L = ['0001101', '0011001', '0010011', '0111101', '0100011', '0110001', '0101111', '0111011', '0110111', '0001011']
const G = ['0100111', '0110011', '0011011', '0100001', '0011101', '0111001', '0000101', '0010001', '0001001', '0010111']
const R = L.map((p) => p.replace(/./g, (b) => (b === '0' ? '1' : '0')))
const PARITY = ['LLLLLL', 'LLGLGG', 'LLGGLG', 'LLGGGL', 'LGLLGG', 'LGGLLG', 'LGGGLL', 'LGLGLG', 'LGLGGL', 'LGGLGL']
export const ean13Check = (d12: string) => { const s = d12.split('').reduce((a, c, i) => a + Number(c) * (i % 2 ? 3 : 1), 0); return String((10 - (s % 10)) % 10) }
export const isEan13 = (v: string) => /^\d{13}$/.test(v) && ean13Check(v.slice(0, 12)) === v[12]
/** رشتهٔ ماژول‌ها (۱ = میله) برای EAN-13 */
export function ean13(v: string): string {
  const d = /^\d{12}$/.test(v) ? v + ean13Check(v) : v
  if (!isEan13(d)) throw new Error('بارکد EAN-13 نامعتبر است')
  const par = PARITY[+d[0]]
  let m = '101'
  for (let i = 1; i <= 6; i++) m += (par[i - 1] === 'L' ? L : G)[+d[i]]
  m += '01010'
  for (let i = 7; i <= 12; i++) m += R[+d[i]]
  return m + '101'
}
/** کد داخلی بعدی با قالب و شمارندهٔ تنظیمات: GH-P-000123 یا GH-U-0012345 */
export const nextCode = (prefix: string, n: number, digits: number) => `${prefix}${String(n).padStart(digits, '0')}`
